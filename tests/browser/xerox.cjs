/* Xerox/lime workflow in a real browser with the real local MCP server. */
const {chromium} = require('playwright');
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');

const ROOT = path.resolve(__dirname, '../..');
const OUT = path.join(ROOT, 'work/xerox-browser-verification');
const BASE = process.env.QCB_XEROX_TEST_URL || 'http://127.0.0.1:8786';
assert.equal(new URL(BASE).hostname, '127.0.0.1');
fs.mkdirSync(OUT, {recursive:true});
const checks = [], errors = [];
let browser;
const record = name => { checks.push(name); console.log(name); };

(async () => {
  browser = await chromium.launch({headless:true, executablePath:'/usr/bin/chromium', args:['--disable-dev-shm-usage']});
  const context = await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true});
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto(BASE);
  let frame = page.frames().find(item => item.url().endsWith('/ui'));
  await frame.locator('#demoHelper').waitFor({state:'visible'});
  const draft = () => frame.evaluate(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent);
  const waitDraft = predicate => frame.waitForFunction(predicate);
  const preview = () => frame.locator('#image svg[data-visual-grammar="urban"]');
  const toolResponse = name => page.waitForResponse(response => new URL(response.url()).pathname === '/call' && response.request().method() === 'POST' && response.request().postDataJSON().name === name);
  const waitPreview = async () => {
    await preview().waitFor();
    await frame.waitForFunction(() => !document.querySelector('#submit')?.dataset.busy);
  };
  const downloadPng = async (filename, expectedWidth, expectedHeight) => {
    const downloaded = page.waitForEvent('download');
    await frame.locator('#produce').click();
    const item = await downloaded;
    const target = path.join(OUT, filename);
    await item.saveAs(target);
    const png = fs.readFileSync(target);
    assert.equal(png.subarray(1,4).toString(), 'PNG');
    assert.equal(png.readUInt32BE(16), expectedWidth);
    assert.equal(png.readUInt32BE(20), expectedHeight);
    return target;
  };

  await frame.locator('#text').fill('Le idee migliori nascono dalle persone.');
  await frame.locator('[data-style-choice="urban-xerox"]').click();
  await waitPreview();
  await waitDraft(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.composition?.artwork_id === 'urban-xerox-lime-v1');
  const expectedArtwork = `data:image/png;base64,${fs.readFileSync(path.join(ROOT, 'assets/urban/urban-xerox-lime-v1.png')).toString('base64')}`;
  const initialSvg = await preview().evaluate(svg => ({font:svg.querySelector('style')?.textContent.includes('Barlow Condensed Black'), artwork:svg.querySelector('image.urban-artwork')?.getAttribute('href')}));
  assert.equal(initialSvg.font, true);
  assert.equal(initialSvg.artwork, expectedArtwork);
  assert.equal((await draft()).brand_kit, null);
  assert.equal(await frame.locator('#ribbonProposals [data-composition-id]').count(), 1);
  record('Xerox uses the packaged artwork, default condensed font, and one proposal');

  await frame.locator('[data-style-choice="urban"]').click();
  await waitPreview();
  assert.equal(await frame.locator('#ribbonProposals [data-composition-id]').count(), 3);
  await frame.locator('[data-style-choice="urban-xerox"]').click();
  await waitPreview();
  record('Geometric Urban still exposes its three native compositions');

  await frame.locator('#attributionDecision').selectOption('named');
  await frame.locator('#attribution').fill('Marta Rossi');
  await frame.locator('#quoteFontSize').fill('82');
  await frame.locator('#quoteFontSize').dispatchEvent('change');
  await waitDraft(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.quote_font_size === 82);
  await frame.locator('#quoteSizeAuto').click();
  await frame.locator('#authorFontSize').fill('27');
  await frame.locator('#authorFontSize').dispatchEvent('change');
  await waitDraft(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.author_font_size === 27);
  const sizedPreview = toolResponse('preview_quote_card');
  await frame.locator('#quoteFontSize').fill('82');
  await frame.locator('#quoteFontSize').dispatchEvent('change');
  await sizedPreview;
  await waitPreview();
  await frame.locator('#brandLibrary summary').click();
  await frame.locator('#brandName').fill('Font prova');
  await frame.locator('#brandFontFamily').fill('Barlow');
  await frame.locator('#brandRegular').setInputFiles(path.join(ROOT, 'assets/card-editor/fonts/Barlow-Regular.ttf'));
  await frame.locator('#brandBold').setInputFiles(path.join(ROOT, 'assets/card-editor/fonts/Barlow-Bold.ttf'));
  const logoPath = path.join(OUT, 'brand-mark.svg');
  fs.writeFileSync(logoPath, '<svg xmlns="http://www.w3.org/2000/svg" width="120" height="32" viewBox="0 0 120 32"><rect width="120" height="32" fill="#171714"/></svg>');
  await frame.locator('#brandLogo').setInputFiles(logoPath);
  await frame.locator('#applyBrand').click();
  await frame.waitForFunction(() => Boolean(document.querySelector('#brandFeedback').textContent.trim()));
  assert.match(await frame.locator('#brandFeedback').textContent(), /^Brand assets checked/);
  await frame.waitForFunction(() => [...document.querySelectorAll('#image svg image')].some(image => (image.getAttribute('href') || image.getAttribute('xlink:href') || '').startsWith('data:image/svg+xml;base64,')));
  const uploadedLogo = await preview().evaluate(svg => [...svg.querySelectorAll('image')].map(image => image.getAttribute('href') || image.getAttribute('xlink:href')).find(href => href?.startsWith('data:image/svg+xml;base64,')) || '');
  assert.ok(uploadedLogo.length > 'data:image/svg+xml;base64,'.length);
  await waitDraft(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.brand_kit?.name === 'Font prova');
  const branded = await draft();
  assert.equal(branded.quote_font_size, 82);
  assert.equal(branded.author_font_size, 27);
  assert.equal(branded.composition.artwork_id, 'urban-xerox-lime-v1');
  assert.ok(branded.brand_kit.font.regular.data_base64);
  record('Manual and automatic sizing coexist with uploaded font and logo');

  await frame.locator('#cardLibrary summary').click();
  await frame.locator('#baseName').fill('Xerox personale');
  await frame.locator('#saveBase').click();
  const store = await frame.evaluate(() => JSON.parse(localStorage.getItem('quote-card-builder.bases.v1')));
  const savedBase = store.bases.find(item => item.name === 'Xerox personale');
  assert.equal(savedBase.design.composition.artwork_id, 'urban-xerox-lime-v1');
  assert.ok(!JSON.stringify(savedBase.design).includes('data:image/png;base64'));
  const baseFile = page.waitForEvent('download');
  await frame.locator('#exportBase').click();
  await (await baseFile).saveAs(path.join(OUT, 'personal-base.json'));
  const savedJson = fs.readFileSync(path.join(OUT, 'personal-base.json'), 'utf8');
  assert.match(savedJson, /urban-xerox-lime-v1/);
  assert.ok(!savedJson.includes('data:image/png;base64'));
  assert.ok(savedJson.includes('data_base64')); // uploaded brand font remains portable
  record('Personal base stores the artwork identifier and portable brand font only');

  await frame.locator('#exportProject').click();
  const project = JSON.parse(await frame.locator('#projectJson').inputValue());
  fs.writeFileSync(path.join(OUT, 'project.json'), JSON.stringify(project));
  assert.equal(project.draft.composition.artwork_id, 'urban-xerox-lime-v1');
  assert.ok(!JSON.stringify(project.draft.composition).includes('base64'));
  assert.ok(!JSON.stringify(project).includes('data:image/png;base64'));
  assert.equal(project.draft.attribution, 'Marta Rossi');
  assert.ok(project.draft.brand_kit.font.regular.data_base64);
  await frame.locator('#text').fill('Le idee crescono quando le persone si incontrano.');
  await frame.locator('#attributionDecision').selectOption('named');
  await frame.locator('#attribution').fill('Luca Bianchi');
  await waitPreview();
  const importResponse = toolResponse('preview_quote_card');
  await frame.locator('#projectFile').setInputFiles(path.join(OUT, 'project.json'));
  await importResponse;
  await frame.waitForFunction(() => document.querySelector('#baseFeedback').textContent.startsWith('Project restored'));
  await waitPreview();
  const restored = await draft();
  assert.equal(restored.text, project.draft.text);
  assert.equal(restored.attribution, project.draft.attribution);
  assert.equal(restored.composition.artwork_id, 'urban-xerox-lime-v1');
  assert.deepEqual(restored.brand_kit, project.draft.brand_kit);
  assert.equal(restored.quote_font_size, 82);
  record('Project import restores Xerox, edited quote, author, font and brand');

  await frame.locator('[data-reuse-mode="card"]').first().click();
  await frame.locator('#reuseText').fill('Le idee crescono quando le persone si incontrano.');
  await frame.locator('#reuseAuthor').fill('Autore nuovo');
  await frame.locator('#reuseConfirm').click();
  await waitDraft(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.text === 'Le idee crescono quando le persone si incontrano.');
  await waitPreview();
  const reused = await draft();
  assert.equal(reused.composition.artwork_id, 'urban-xerox-lime-v1');
  assert.equal(reused.attribution, 'Autore nuovo');
  assert.equal(reused.quote_font_size, null);
  assert.deepEqual(reused.brand_kit, project.draft.brand_kit);
  record('Saved base starts a new quote while retaining Xerox art and uploaded brand');
  await frame.locator('#text').fill('Le idee crescono quando le persone si incontrano.');
  await frame.locator('#attributionDecision').selectOption('named');
  await frame.locator('#attribution').fill('Autore nuovo');
  await waitPreview();
  await page.reload();
  frame = page.frames().find(item => item.url().endsWith('/ui'));
  const restoredFrame = frame;
  await restoredFrame.locator('#image svg[data-visual-grammar="urban"]').waitFor();
  await restoredFrame.waitForFunction(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.text === 'Le idee crescono quando le persone si incontrano.');
  const reloadDraft = await restoredFrame.evaluate(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent);
  assert.equal(reloadDraft.composition.artwork_id, 'urban-xerox-lime-v1');
  assert.deepEqual(reloadDraft.brand_kit, project.draft.brand_kit);
  record('Reload restores the saved Xerox draft and brand assets');

  await downloadPng('card-4x5.png', 1440, 1800);
  await restoredFrame.locator('#format').selectOption('1x1');
  await restoredFrame.locator('#image svg[data-visual-grammar="urban"]').waitFor();
  await downloadPng('card-1x1.png', 1440, 1440);
  await page.screenshot({path:path.join(OUT, 'square.png'), fullPage:true});
  await restoredFrame.locator('#format').selectOption('9x16');
  await restoredFrame.locator('#image svg[data-visual-grammar="urban"]').waitFor();
  await downloadPng('card-9x16.png', 1440, 2560);
  await page.screenshot({path:path.join(OUT, 'story.png'), fullPage:true});
  record('PNG downloads render correctly in portrait, square, and story formats');

  await page.setViewportSize({width:375,height:844});
  await page.screenshot({path:path.join(OUT, 'mobile.png'), fullPage:true});
  const overflow = await restoredFrame.evaluate(() => ({width:document.documentElement.scrollWidth, viewport:innerWidth}));
  assert.ok(overflow.width <= overflow.viewport, `horizontal overflow: ${overflow.width}px > ${overflow.viewport}px`);
  assert.equal(errors.length, 0, errors.join('\n'));
  fs.writeFileSync(path.join(OUT, 'report.json'), JSON.stringify({host:'simulated MCP host, real local tools and renderer',checks,errors},null,2));
})().catch(error => {console.error(error);process.exitCode=1;}).finally(async () => {if(browser) await browser.close();});
