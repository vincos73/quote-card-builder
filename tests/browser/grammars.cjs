/* Real browser, simulated MCP host, real server tools and PNG canvas export. */
const {chromium} = require('playwright');
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const ROOT = path.resolve(__dirname, '../..');
const OUT = path.join(ROOT, 'work/grammars-verification');
const BASE = process.env.QCB_GRAMMAR_TEST_URL || 'http://127.0.0.1:8786';
assert.equal(new URL(BASE).hostname, '127.0.0.1');
fs.mkdirSync(OUT, {recursive:true});
const checks = [], errors = [];
let browser;
const record = name => { checks.push(name); console.log(name); };
(async () => {
  browser = await chromium.launch({headless:true, executablePath:'/usr/bin/chromium', args:['--disable-dev-shm-usage']});
  const context = await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true});
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto(BASE);
  const frame = page.frames().find(f => f.url().endsWith('/ui'));
  await frame.locator('#demoHelper').waitFor({state:'visible'});
  const draft = () => frame.evaluate(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent);
  const waitDraft = predicate => frame.waitForFunction(predicate);
  const toolResponse = name => page.waitForResponse(r => new URL(r.url()).pathname === '/call' && r.request().method() === 'POST' && r.request().postDataJSON().name === name);
  await frame.locator('#text').fill('Le idee migliori nascono dalle persone.');
  await frame.locator('[data-style-choice="urban"]').click();
  await frame.locator('#image svg[data-visual-grammar="urban"]').waitFor();
  await frame.locator('#ribbonProposals [data-composition-id]').nth(2).waitFor();
  assert.equal(await frame.locator('#ribbonProposals [data-composition-id]').count(), 3);
  record('Urban exposes three native compositions');
  await frame.locator('#ribbonProposals [data-composition-id]').nth(2).click();
  await waitDraft(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.composition?.id === 'urban-stacked-columns');
  const scene = (await draft()).composition;
  await frame.locator('#quoteFontSize').fill('92');
  await frame.locator('#quoteFontSize').dispatchEvent('change');
  await frame.locator('#authorFontSize').fill('32');
  await frame.locator('#authorFontSize').dispatchEvent('change');
  await frame.locator('#brandLibrary summary').click();
  await frame.locator('#brandName').fill('Brand di prova');
  await frame.locator('#brandFontFamily').fill('Barlow');
  await frame.locator('#brandRegular').setInputFiles(path.join(ROOT, 'assets/card-editor/fonts/Barlow-Regular.ttf'));
  await frame.locator('#brandBold').setInputFiles(path.join(ROOT, 'assets/card-editor/fonts/Barlow-Bold.ttf'));
  await frame.locator('#brandLogo').setInputFiles(path.join(ROOT, 'assets/card-editor/vincos-lockup-white.svg'));
  await frame.locator('#applyBrand').click();
  await frame.waitForFunction(() => document.querySelector('#brandFeedback').textContent.startsWith('Brand assets checked'));
  await frame.locator('#image svg image').waitFor();
  await waitDraft(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.brand_kit?.name === 'Brand di prova');
  const branded = await draft();
  assert.ok(branded.brand_kit.font.regular.data_base64);
  assert.equal(branded.quote_font_size, 92);
  assert.deepEqual(branded.composition, scene);
  record('Real font and vector logo upload preserve chosen geometry and manual sizes');
  await page.waitForFunction(() => contexts.at(-1)?.structuredContent?.modelContent?.brand_kit_attached === true);
  const model = await page.evaluate(() => contexts.at(-1).structuredContent.modelContent);
  assert.ok(!JSON.stringify(model).includes('data_base64'));
  assert.equal(model.brand_summary.font_family, 'Barlow');
  record('Model context excludes asset binaries while local draft retains them');

  const chatResult = await page.evaluate(async model => {
    const result = await fetch('/call', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({name:'quote_card_builder_update_editor', arguments:{base_revision:model._editor_revision,base_snapshot:model,patch:{attribution:'Autore fornito'}}})}).then(r => r.json());
    document.querySelector('iframe').contentWindow.postMessage({jsonrpc:'2.0',method:'ui/notifications/tool-result',params:result},location.origin);
    return result;
  }, model);
  assert.equal(chatResult.structuredContent.deferred_render, true);
  await waitDraft(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.attribution === 'Autore fornito');
  assert.deepEqual((await draft()).brand_kit, branded.brand_kit);
  assert.deepEqual((await draft()).composition, scene);
  await frame.locator('#image svg image').waitFor();
  record('Chat edit applies to the live branded draft and triggers a real preview');

  await frame.locator('#cardLibrary summary').click();
  await frame.locator('#baseName').fill('Urban personale');
  await frame.locator('#saveBase').click();
  const bases = await frame.evaluate(() => JSON.parse(localStorage.getItem('quote-card-builder.bases.v1')));
  const saved = bases.bases[0];
  assert.equal(saved.schema, 'qcb-personal-base');
  assert.ok(!('text' in saved.design));
  assert.ok(!('styles' in saved.design));
  assert.deepEqual(saved.design.composition, scene);
  const baseDownload = page.waitForEvent('download');
  await frame.locator('#exportBase').click();
  await (await baseDownload).saveAs(path.join(OUT,'personal-base.json'));
  await frame.locator('#exportProject').click();
  const project = JSON.parse(await frame.locator('#projectJson').inputValue());
  fs.writeFileSync(path.join(OUT,'project.json'),JSON.stringify(project));
  assert.equal(project.draft.attribution, 'Autore fornito');
  assert.equal(project.draft.quote_font_size,92);
  assert.ok(project.draft.brand_kit.logo.data_base64);
  record('Base export excludes editorial content and project export preserves the complete draft');

  await frame.locator('[data-reuse-mode="card"]').first().click();
  await frame.locator('#reuseText').fill('Una frase nuova nello stesso linguaggio.');
  await frame.locator('#reuseAuthor').fill('');
  await frame.locator('#reuseConfirm').click();
  await waitDraft(() => JSON.parse(localStorage.getItem('quote-card-builder.workspace.v1')).modelContent.text === 'Una frase nuova nello stesso linguaggio.');
  const reused = await draft();
  assert.deepEqual(reused.composition,scene);
  assert.equal(reused.attribution,'');
  assert.equal(reused.quote_font_size,null);
  assert.deepEqual(reused.styles,[]);
  assert.ok(reused.brand_kit.logo);
  record('New quote reuses exact design and brand, clears old ranges and respects optional author');
  await frame.locator('[data-reuse-mode="model"]').first().click();
  await frame.locator('#reuseConfirm').click();
  await page.waitForFunction(() => messages.length > 0);
  assert.match(await page.evaluate(() => messages.at(-1).content[0].text), /Create three new compositions/);
  assert.ok(!(await page.evaluate(() => JSON.stringify(messages))).includes('data_base64'));
  record('Create in this style explicitly requests model compositions without binary assets');
  const imported = toolResponse('preview_quote_card');
  await frame.locator('#projectFile').setInputFiles(path.join(OUT,'project.json'));
  await imported;
  await frame.waitForFunction(() => document.querySelector('#baseFeedback').textContent.startsWith('Project restored'));
  await frame.locator('#image svg image').waitFor();
  const restored = await draft();
  assert.equal(restored.text,project.draft.text);
  assert.deepEqual(restored.brand_kit,project.draft.brand_kit);
  assert.equal(restored.quote_font_size,92);
  record('Project import restores exact composition, content, sizes and embedded assets');
  const pngDownload = page.waitForEvent('download');
  await frame.locator('#produce').click();
  await (await pngDownload).saveAs(path.join(OUT,'card.png'));
  const png = fs.readFileSync(path.join(OUT,'card.png'));
  assert.equal(png.subarray(1,4).toString(),'PNG');
  assert.equal(png.readUInt32BE(16),1440);
  assert.equal(png.readUInt32BE(20),1800);
  record('PNG download rasterizes the current branded Urban card');
  await frame.locator('#brandLibrary summary').click();
  await frame.locator('#cardLibrary summary').click();
  await page.screenshot({path:path.join(OUT,'desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(OUT,'mobile.png'),fullPage:true});
  assert.equal(errors.length,0,errors.join('\n'));
  fs.writeFileSync(path.join(OUT,'report.json'),JSON.stringify({host:'simulated MCP host',checks,errors},null,2));
})().catch(error => {console.error(error);process.exitCode=1;}).finally(async () => {if(browser) await browser.close();});
